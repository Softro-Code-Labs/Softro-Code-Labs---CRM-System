/* eslint-disable @typescript-eslint/no-require-imports -- plain Node script */
// Generates src/lib/seal-artwork.ts: the Softro Code Labs company seal as plain vector paths.
// The lettering is turned into outlines with the Geist font, so the seal looks the same
// in the browser and in PDFs and can't be edited as text.
//   node scripts/make-seal.cjs
const path = require("node:path");
const fs = require("node:fs");

const root = path.join(__dirname, "..");
// fontkit comes with @react-pdf/renderer; resolve it through that package.
const fontkit = require(
  require.resolve("fontkit", { paths: [path.dirname(require.resolve("@react-pdf/font", { paths: [path.dirname(require.resolve("@react-pdf/renderer"))] }))] }),
);
const font = (w) => fontkit.openSync(path.join(root, `src/assets/fonts/Geist-${w}.ttf`));
const fonts = { SemiBold: font("SemiBold"), Bold: font("Bold") };

const TOP = "SOFTRO CODE LABS";
const BOTTOM = "(PVT) LTD  ·  SRI LANKA";

const C = 150; // the seal is drawn in a 300 × 300 box
const r2 = (n) => Math.round(n * 100) / 100;

function glyphPath(glyph, map) {
  let d = "";
  for (const { command, args } of glyph.path.commands) {
    const pts = [];
    for (let i = 0; i < args.length; i += 2) pts.push(map(args[i], args[i + 1]).map(r2).join(" "));
    d += { moveTo: "M", lineTo: "L", quadraticCurveTo: "Q", bezierCurveTo: "C", closePath: "Z" }[command] + pts.join(" ");
  }
  return d;
}

function measure(text, size, spacing, fnt) {
  const s = size / fnt.unitsPerEm;
  const run = fnt.layout(text);
  const adv = run.positions.map((p) => p.xAdvance * s + spacing);
  return { s, run, adv, W: adv.reduce((a, b) => a + b, 0) - spacing, cap: fnt.capHeight * s };
}

/** Text bent round the circle, centred at the top or bottom and spread across `fit` degrees. */
function arcText(text, { size, rMid, where, weight, fit }) {
  const fnt = fonts[weight];
  let m = measure(text, size, 0, fnt);
  const R = where === "top" ? rMid - m.cap / 2 : rMid + m.cap / 2;
  m = measure(text, size, (((fit * Math.PI) / 180) * R - m.W) / (m.run.glyphs.length - 1), fnt);
  let a = 0;
  let d = "";
  m.run.glyphs.forEach((g, i) => {
    const ox = a;
    d += glyphPath(g, (x, y) => {
      const th = (ox + x * m.s - m.W / 2) / R;
      return where === "top"
        ? [C + (R + y * m.s) * Math.sin(th), C - (R + y * m.s) * Math.cos(th)]
        : [C + (R - y * m.s) * Math.sin(th), C + (R - y * m.s) * Math.cos(th)];
    });
    a += m.adv[i];
  });
  return d;
}

const circle = (cx, cy, r) => `M${r2(cx - r)} ${r2(cy)}a${r} ${r} 0 1 0 ${r2(2 * r)} 0a${r} ${r} 0 1 0 ${r2(-2 * r)} 0Z`;
const ring = (r, w) => circle(C, C, r + w / 2) + circle(C, C, r - w / 2); // filled with even-odd
function dots(r, n, dr) {
  let d = "";
  for (let i = 0; i < n; i++) {
    const a = (2 * Math.PI * i) / n;
    d += circle(C + r * Math.cos(a), C + r * Math.sin(a), dr);
  }
  return d;
}
function star(cx, cy, r) {
  let d = "";
  for (let i = 0; i < 10; i++) {
    const a = (Math.PI / 5) * i - Math.PI / 2;
    const rr = i % 2 ? r * 0.42 : r;
    d += `${i ? "L" : "M"}${r2(cx + rr * Math.cos(a))} ${r2(cy + rr * Math.sin(a))}`;
  }
  return d + "Z";
}

// The Softro mark (same artwork as the website), scaled into the middle of the seal.
const MARK =
  "M111.5 24 L47 54.5 L47 102 L98.5 121.5 L98.5 154 L83 146 L83 121.4 L69 116.3 L69 154.6 L112.6 177 L112.6 78 L98.3 83.2 L98.3 105.9 L83 100.4 L83 83.4 L129 66.4 L129 117 L117 113 L117 127.5 L143.3 137 L143.3 46.8 L112.6 57 L112.6 24 Z M98.3 45.4 L98.3 62.4 L69 73.2 L69 95.2 L61.2 92.8 L61.2 63.5 Z";
function mark(height, cy) {
  const k = height / 153; // the mark spans y 24–177
  return MARK.replace(/(-?[\d.]+) (-?[\d.]+)/g, (_, x, y) => `${r2(C + (Number(x) - 95.15) * k)} ${r2(cy + (Number(y) - 100.5) * k)}`);
}

const paths = [
  ring(143, 6) + ring(134.5, 1.4),
  arcText(TOP, { size: 24, rMid: 114, where: "top", weight: "Bold", fit: 150 }),
  arcText(BOTTOM, { size: 14, rMid: 114, where: "bottom", weight: "SemiBold", fit: 100 }),
  star(C - 114, C, 5.5) + star(C + 114, C, 5.5),
  ring(94, 1.4),
  dots(88, 72, 1.1),
  mark(96, C - 4),
];
// The line under the mark (the company registration number, or "OFFICIAL") is drawn when the
// document is made, from Settings → Company details, so it isn't part of the artwork.

const out = `// Generated by scripts/make-seal.cjs. Don't edit by hand: change the script and run it again.
/** The Softro Code Labs (Pvt) Ltd company seal ("Classic"): vector paths in a ${C * 2} × ${C * 2} box, filled with SEAL_COLOR using the even-odd rule. */
export const SEAL_SIZE = ${C * 2};
export const SEAL_COLOR = "#A70B21";
/** Where the line under the mark goes: centred, baseline at this y, in Geist SemiBold. */
export const SEAL_LABEL = { y: 214, size: 12.5, letterSpacing: 1.4 } as const;
export const SEAL_PATHS: readonly string[] = ${JSON.stringify(paths, null, 2)};
`;
fs.writeFileSync(path.join(root, "src/lib/seal-artwork.ts"), out);
console.log("Wrote src/lib/seal-artwork.ts");
